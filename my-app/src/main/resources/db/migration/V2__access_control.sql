-- DEMO-141: access-control tables, moved here from db/DEMO-129-access-control.sql.
-- Every statement is "if not exists" so it is safe over a database where the tables already exist.
-- Seed rows are created by the application at startup (AccessControlSeeder), not here.

create table if not exists modules (
    id bigint generated by default as identity primary key,
    code varchar(255) not null,
    name varchar(255) not null,
    description varchar(255),
    active boolean not null,
    constraint uk_modules_code unique (code)
);

create table if not exists permissions (
    id bigint generated by default as identity primary key,
    module_id bigint not null references modules (id),
    action varchar(255) not null,
    code varchar(255) not null,
    description varchar(255),
    constraint uk_permissions_code unique (code)
);

create table if not exists roles (
    id bigint generated by default as identity primary key,
    code varchar(255) not null,
    name varchar(255) not null,
    scope varchar(255) not null check (scope in ('PLATFORM', 'FIRM')),
    system boolean not null,
    constraint uk_roles_code unique (code)
);

create table if not exists role_permissions (
    role_id bigint not null references roles (id),
    permission_id bigint not null references permissions (id),
    primary key (role_id, permission_id)
);

create table if not exists user_roles (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id),
    role_id bigint not null references roles (id),
    assigned_by bigint references users (id),
    assigned_at timestamp(6) with time zone not null,
    constraint uk_user_roles_user_role unique (user_id, role_id)
);

create table if not exists firms (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    code varchar(255) not null,
    contact_email varchar(255),
    phone varchar(255),
    address varchar(255),
    status varchar(255) not null check (status in ('ACTIVE', 'INACTIVE')),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_firms_code unique (code)
);
